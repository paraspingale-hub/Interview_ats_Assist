"""
File Name    : report_generator.py
Author       : Piyush Manohar Khairnar
Date         : 10/05/2026

Description  :
This file is responsible for generating and saving
final interview reports of students.

The generated report contains:
1. Student Information
2. Interview Evaluation
3. Technical Feedback
4. Score Analysis
5. Suggestions

The report is automatically stored inside the
'reports' folder with timestamp information.

============================================================
"""

# Import os module
# Used for folder and file operations
import os
import re
from pathlib import Path

# Import datetime module
# Used to generate timestamp for report file
import datetime


REPORTS_DIRECTORY = Path(__file__).resolve().parent / "reports"
QUESTIONS_DIRECTORY = Path(__file__).resolve().parent / "questions"


def _safe_filename_part(value):
    """Keep user-provided names out of generated paths."""
    cleaned = re.sub(r"[^A-Za-z0-9_-]+", "_", str(value).strip())
    return cleaned.strip("_") or "Interview"


def save_questions(student_name, domain, difficulty, questions):
    """Save the generated question set so the interview can reuse it."""
    QUESTIONS_DIRECTORY.mkdir(exist_ok=True)
    timestamp = datetime.datetime.now().strftime("%d_%m_%Y_%H_%M_%S")
    safe_name = _safe_filename_part(student_name)
    filename = QUESTIONS_DIRECTORY / f"Interview_Questions_{safe_name}_{timestamp}.txt"

    with open(filename, "w", encoding="utf-8") as file:
        file.write("=" * 70 + "\n")
        file.write("              SmartHire AI Mock Interview\n")
        file.write("                 Generated Questions\n")
        file.write("=" * 70 + "\n\n")
        file.write(f"Student  : {student_name}\n")
        file.write(f"Domain   : {domain}\n")
        file.write(f"Difficulty: {difficulty}\n\n")
        for index, question in enumerate(questions, start=1):
            file.write(f"{index}. {question}\n")

    return str(filename)


def save_report(student_name, report):
    """
    Function Name : save_report

    Description   :
    This function saves the final interview report
    into a text file inside the reports folder.

    Parameters    :
        student_name : Name of student
        report       : Final generated report

    Return Value :
        Returns generated filename
    """

    # Check whether reports folder exists
    # If not present, create it
    REPORTS_DIRECTORY.mkdir(exist_ok=True)

    # Generate current timestamp
    # Example:
    # 10_05_2026_18_30_45
    timestamp = datetime.datetime.now().strftime(
        "%d_%m_%Y_%H_%M_%S"
    )

    # Replace spaces with underscore
    # to avoid filename issues
    safe_name = student_name.replace(" ", "_")

    # Generate report filename
    # AI_Agent added in filename
    filename = REPORTS_DIRECTORY / (
        f"AI_Agent_{safe_name}_Interview_Report_{timestamp}.txt"
    )

    # Open file in write mode
    with open(filename, "w", encoding="utf-8") as file:

        # Write branding header into report
        file.write("=" * 70 + "\n")
        file.write("               Infosystems\n")
        file.write("              AI Mock Interview Agent\n")
        file.write("              Generated Interview Report\n")
        file.write("=" * 70 + "\n\n")

        file.write("Author : Paras Rahul Pingale\n")
        file.write("Date   : 10/05/2026\n")

        file.write("=" * 70 + "\n")
        file.write("                  STUDENT REPORT\n")
        file.write("=" * 70 + "\n\n")

        # Write actual interview report
        file.write(report)

        # Add ending footer
        file.write("\n\n")
        file.write("=" * 70 + "\n")
        file.write("Generated By : SmartHire AI_Agent\n")
        file.write("Creator      :  Infosystems\n")
        file.write("=" * 70 + "\n")

    print("\n================================================")
    print("Interview Report Generated Successfully")
    print("Report File :", filename)
    print("================================================")

    # Return generated filename
    return str(filename)
